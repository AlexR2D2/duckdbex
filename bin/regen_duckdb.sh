#!/usr/bin/env bash
set -euo pipefail

# Regenerate c_src/duckdb from duckdb/duckdb at <ref>.
#
# Usage: bin/regen_duckdb.sh <ref> [version]   e.g. bin/regen_duckdb.sh v1.5.5
#
# <ref> is a duckdb/duckdb tag or commit. [version] defaults to <ref> with a
# leading "v" stripped when <ref> looks like a release tag; pass it explicitly
# for non-tag refs (it becomes DUCKDB_VERSION, e.g. "1.6.0-dev").
#
# Requirements: gh CLI (authenticated), python3, rsync.
#
# package_build.py has no CLI. The driver script
# (bin/generate_duckdb_sources.py) calls build_package() directly, and the
# two SETUPTOOLS_SCM_* variables pin the version strings that the generator
# bakes into pragma_version.cpp so output is byte-reproducible:

#   - SETUPTOOLS_SCM_PRETEND_VERSION -> DUCKDB_VERSION
#   - SETUPTOOLS_SCM_PRETEND_HASH    -> DUCKDB_SOURCE_ID
#
# Upgrading DuckDB (e.g. v1.5.5 -> v1.6.0):
#
#   1. bin/regen_duckdb.sh v1.6.0
#   2. git diff --stat c_src/duckdb/   # review the delta
#   3. mix test                        # full suite
#   4. commit the regenerated tree
#
# The Makefile reads .sources / .include_dirs from the generated tree, so a
# version bump normally needs no Makefile changes. gh is used for two things:
# downloading the upstream tarball and resolving <ref> to its commit hash
# (which becomes DUCKDB_SOURCE_ID).

REF="${1:?usage: bin/regen_duckdb.sh <ref> [version]}"
if [[ "$REF" =~ ^v[0-9]+\.[0-9]+\.[0-9]+ ]]; then
  VERSION="${2:-${REF#v}}"
elif [ -n "${2:-}" ]; then
  VERSION="$2"
else
  echo "ERROR: <ref> is not a release tag (vX.Y.Z); pass the version explicitly" >&2
  exit 1
fi
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TARGET="$ROOT/c_src/duckdb"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

echo "==> fetching duckdb/duckdb at ${REF}"
gh api "repos/duckdb/duckdb/tarball/${REF}" > "$WORK/src.tar.gz"
tar -xzf "$WORK/src.tar.gz" -C "$WORK"
SRC_DIR="$(find "$WORK" -maxdepth 1 -type d -name 'duckdb-*' -print -quit)"

SOURCE_ID="$(gh api "repos/duckdb/duckdb/commits/${REF}" --jq '.sha' | cut -c1-10)"
echo "==> generating (version=${VERSION}, source_id=${SOURCE_ID})"
mkdir -p "$WORK/out"
(
  cd "$SRC_DIR"
  SETUPTOOLS_SCM_PRETEND_VERSION="$VERSION" \
    SETUPTOOLS_SCM_PRETEND_HASH="$SOURCE_ID" \
    python3 "$ROOT/bin/generate_duckdb_sources.py" "$WORK/out"
)

echo "==> syncing into duckdbex/c_src/duckdb"
mkdir -p "$TARGET"
rsync -a --delete "$WORK/out/" "$TARGET/"

cat > "$TARGET/PROVENANCE.md" <<EOF
# Vendored DuckDB sources

Everything in this directory is 100% generated code. Do not edit by hand;
regenerate instead:

    bin/regen_duckdb.sh ${REF}

- upstream: <https://github.com/duckdb/duckdb>
- ref: ${REF}
- source id: ${SOURCE_ID}
- duckdb version: ${VERSION}
- generated by: upstream \`scripts/package_build.py\` (\`build_package\`) via
  \`bin/generate_duckdb_sources.py\`
- extensions: core_functions, parquet (upstream build baseline)
- generation options: \`linenumbers=false\`, \`unity_count=32\` (upstream
  defaults), \`folder_name=""\`
- version strings are baked into \`src/function/table/version/pragma_version.cpp\`
  by the generator, pinned via \`SETUPTOOLS_SCM_PRETEND_VERSION\` /
  \`SETUPTOOLS_SCM_PRETEND_HASH\`
EOF

echo "==> done"
echo "    verify: git diff --stat c_src/duckdb/"
echo "    build:  mix test"